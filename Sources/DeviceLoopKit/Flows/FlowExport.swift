import DeviceLoopProtocol
import Foundation

/// Turns a flow into the Swift source of one XCTestCase class with one UI test method.
public enum FlowExport {
    public struct Output: Sendable, Equatable {
        public var className: String
        public var source: String
        /// Every exported step, for example `steps[3] tap`.
        public var supported: [String]
        /// Exported steps that depend on screen geometry or timing, with the reason.
        public var fragile: [String]
    }

    /// Generates the test class. Throws bad_arguments listing every step the export cannot represent.
    public static func source(_ flow: Flow, className: String? = nil) throws -> Output {
        let base = typeName(flow.name)
        let className = className ?? "\(base)FlowTests"
        guard className.wholeMatch(of: /[A-Za-z_][A-Za-z0-9_]*/) != nil else {
            throw DeviceLoopError(
                .badArguments, "\(className) is not a Swift type name.", fix: "Use letters, digits and underscores, starting with a letter."
            )
        }
        var main = StepWriter(bundleID: flow.app.bundleID)
        if flow.reset == .reinstall {
            main.unsupported.append("reset reinstall: XCUIApplication cannot install or uninstall apps.")
        }
        main.write(flow.setup, phase: "setup")
        main.write(flow.steps, phase: "steps")
        var cleanup = StepWriter(bundleID: main.bundleID)
        cleanup.write(flow.cleanup, phase: "cleanup")
        let unsupported = main.unsupported + cleanup.unsupported
        guard unsupported.isEmpty else {
            throw DeviceLoopError(
                .badArguments, "Flow \(flow.name) cannot be exported to XCTest.",
                fix: "Change or remove each step in Detail, then export again.", detail: unsupported.joined(separator: "\n"))
        }

        var lines = [
            "// Generated by deviceloop flow export from flow \(literal(flow.name)).",
            "",
            "import XCTest",
            "",
            "final class \(className): XCTestCase {",
            "    @MainActor",
            "    func test\(base)() throws {",
            "        continueAfterFailure = false",
        ]
        if !flow.cleanup.isEmpty {
            lines += ["        addTeardownBlock { @MainActor in", "            self.continueAfterFailure = true"]
            if flow.cleanup.contains(where: \.usesApp) {
                lines.append("            \(cleanup.declaration)")
            }
            lines += cleanup.lines.map { "            \($0)" }
            lines.append("        }")
        }
        // activate() starts a stopped app with the arguments of an earlier launch().
        let start = flow.reset == .none ? "if app.state == .notRunning { app.launch() } else { app.activate() }" : "app.launch()"
        lines.append("        \(main.declaration)")
        lines += launch(arguments: flow.app.arguments, environment: flow.app.environment, start).map { "        \($0)" }
        lines.append("")
        lines += main.lines.map { "        \($0)" }
        lines += [
            "    }",
            "}",
            "",
            "/// The one element `query` matches, after waiting up to `timeout` seconds for exactly one match.",
            "@MainActor",
            "private func uniqueElement(_ query: XCUIElementQuery, timeout: TimeInterval, file: StaticString = #filePath, line: UInt = #line)",
            "    -> XCUIElement",
            "{",
            "    let deadline = Date().addingTimeInterval(timeout)",
            "    XCTAssertTrue(query.firstMatch.waitForExistence(timeout: timeout), \"No element matches the query.\", file: file, line: line)",
            "    while query.count != 1, Date() < deadline { RunLoop.current.run(until: Date().addingTimeInterval(0.2)) }",
            "    XCTAssertEqual(query.count, 1, \"The query must match one element.\", file: file, line: line)",
            "    return query.element",
            "}",
            "",
        ]
        return Output(
            className: className, source: lines.joined(separator: "\n"), supported: main.supported + cleanup.supported,
            fragile: main.fragile + cleanup.fragile)
    }

    /// The flow name as an UpperCamelCase Swift type name, ASCII letters and digits only.
    static func typeName(_ name: String) -> String {
        let words = name.split { !($0.isASCII && ($0.isLetter || $0.isNumber)) }
        let base = words.map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
        return base.first?.isLetter == true ? base : "Flow\(base)"
    }

    /// A Swift string literal that holds `text` exactly. Quotes, backslashes, control characters and non-ASCII are escaped.
    static func literal(_ text: String) -> String {
        var escaped = "\""
        for scalar in text.unicodeScalars {
            switch scalar {
                case "\"": escaped += "\\\""
                case "\\": escaped += "\\\\"
                case "\n": escaped += "\\n"
                case "\r": escaped += "\\r"
                case "\t": escaped += "\\t"
                case " " ... "~": escaped.unicodeScalars.append(scalar)
                default: escaped += "\\u{\(String(scalar.value, radix: 16, uppercase: true))}"
            }
        }
        return escaped + "\""
    }

    /// `NSPredicate(format:)` source that compares `key` with each of `forms`.
    static func predicate(_ key: String, _ comparison: String, _ forms: [String]) -> String {
        let format = forms.map { _ in "\(key) \(comparison) %@" }.joined(separator: " OR ")
        return "NSPredicate(format: \"\(format)\", \(forms.map(literal).joined(separator: ", ")))"
    }

    /// Sets launch arguments and environment, then runs the `start` statement.
    static func launch(arguments: [String], environment: [String: String], _ start: String = "app.launch()") -> [String] {
        let pairs = environment.sorted { $0.key < $1.key }.map { "\(literal($0.key)): \(literal($0.value))" }
        return [
            "app.launchArguments = [\(arguments.map(literal).joined(separator: ", "))]",
            "app.launchEnvironment = [\(pairs.isEmpty ? ":" : pairs.joined(separator: ", "))]",
            start,
        ]
    }

    /// Names of XCUIElement.ElementType cases, as in Runner/UITests/ElementTypes.swift.
    static let elementTypes: Set<String> = [
        "any", "other", "application", "group", "window", "sheet", "alert", "dialog", "button", "radioButton", "checkBox", "popUpButton",
        "menuButton", "toolbarButton", "popover", "keyboard", "key", "navigationBar", "tabBar", "tabGroup", "toolbar", "statusBar", "table",
        "cell", "collectionView", "slider", "pageIndicator", "progressIndicator", "activityIndicator", "segmentedControl", "picker",
        "pickerWheel", "switch", "toggle", "link", "image", "icon", "searchField", "scrollView", "staticText", "textField",
        "secureTextField", "datePicker", "textView", "menu", "menuItem", "map", "webView", "stepper", "tab", "ratingIndicator",
    ]
}

/// Writes steps as XCTContext activities and tracks the app that later steps act on.
private struct StepWriter {
    struct Unsupported: Error {
        let reason: String
    }

    /// The app `app` starts as.
    let start: String
    /// The app the next step acts on.
    var bundleID: String
    /// Whether a launch step switched `app` to another bundle ID.
    var reassigns = false
    var lines: [String] = []
    var supported: [String] = []
    var fragile: [String] = []
    var unsupported: [String] = []

    init(bundleID: String) {
        start = bundleID
        self.bundleID = bundleID
    }

    var declaration: String {
        "\(reassigns ? "var" : "let") app = XCUIApplication(bundleIdentifier: \(FlowExport.literal(start)))"
    }

    mutating func write(_ steps: [FlowStep], phase: String) {
        for (index, step) in steps.enumerated() {
            let name = "\(phase)[\(index)] \(step.kind)"
            do {
                let body = try self.body(step, name)
                let isThrowing = if case .ui(.openURL) = step.action { true } else { false }
                let activity = if case .screenshot = step.action { "activity" } else { "_" }
                lines.append(
                    "\(isThrowing ? "try " : "")XCTContext.runActivity(named: \(FlowExport.literal(name))) { \(activity) in")
                lines += body.map { "    \($0)" }
                lines.append("}")
                supported.append(name)
            } catch {
                unsupported.append("\(name): \(error.reason)")
            }
        }
    }

    private mutating func body(_ step: FlowStep, _ name: String) throws(Unsupported) -> [String] {
        let timeout = Self.seconds(step.timeoutMs)
        switch step.action {
            case .ui(.tap(let target, let count, let holdMs)):
                let gesture = holdMs.map { "press(forDuration: \(Self.seconds($0)))" } ?? (count == 2 ? "doubleTap()" : "tap()")
                guard let point = target.point else { return ["\(try element(target, timeout)).\(gesture)"] }
                fragile.append("\(name): a point target depends on the screen size and layout.")
                return ["\(Self.coordinate(point)).\(gesture)"]
            case .ui(.swipe(let direction, let on, let velocity)):
                let receiver = if let on { try element(on, timeout) } else { "app" }
                let argument = velocity.map { "velocity: XCUIGestureVelocity(rawValue: \(Self.number($0)))" } ?? ""
                return ["\(receiver).swipe\(direction.prefix(1).uppercased() + direction.dropFirst())(\(argument))"]
            case .ui(.drag(let from, let to, let velocity, let holdMs)):
                fragile.append("\(name): drag points depend on the screen size and layout.")
                let speed = velocity.map { "XCUIGestureVelocity(rawValue: \(Self.number($0)))" } ?? ".default"
                return [
                    "let start = \(Self.coordinate(from))",
                    "let end = \(Self.coordinate(to))",
                    "start.press(forDuration: 0.05, thenDragTo: end, withVelocity: \(speed), thenHoldForDuration: \(Self.seconds(holdMs ?? 0)))",
                ]
            case .ui(.type(let text, let into, let clear)):
                if clear { throw Unsupported(reason: "clear is not exported.") }
                guard let into else { return ["app.typeText(\(FlowExport.literal(text)))"] }
                return ["let element = \(try element(into, timeout))", "element.tap()", "element.typeText(\(FlowExport.literal(text)))"]
            case .ui(.press(let button)):
                return ["XCUIDevice.shared.press(.\(button))"]
            case .ui(.launch(let bundleID, let arguments, let environment)):
                let launch = FlowExport.launch(arguments: arguments, environment: environment)
                guard bundleID != self.bundleID else { return launch }
                self.bundleID = bundleID
                reassigns = true
                return ["app = XCUIApplication(bundleIdentifier: \(FlowExport.literal(bundleID)))"] + launch
            case .ui(.openURL(let url)):
                return ["XCUIDevice.shared.system.open(try XCTUnwrap(URL(string: \(FlowExport.literal(url)))))"]
            case .ui(.sleep(let ms)):
                fragile.append("\(name): a fixed sleep depends on timing.")
                return ["Thread.sleep(forTimeInterval: \(Self.seconds(ms)))"]
            case .assert(let query, let assertion):
                let matches = try self.query(query)
                let element = "let element = uniqueElement(\(matches), timeout: \(timeout))"
                switch assertion {
                    case .exists:
                        return ["_ = uniqueElement(\(matches), timeout: \(timeout))"]
                    case .gone:
                        return [
                            "XCTAssertTrue(\(matches).firstMatch.waitForNonExistence(timeout: \(timeout)), \"An element still matches the query.\")"
                        ]
                    case .hittable:
                        return [
                            element,
                            "XCTAssertTrue(element.wait(for: \\.isHittable, toEqual: true, timeout: \(timeout)), \"Not hittable.\")",
                        ]
                    case .enabled:
                        return [
                            element, "XCTAssertTrue(element.wait(for: \\.isEnabled, toEqual: true, timeout: \(timeout)), \"Not enabled.\")",
                        ]
                    case .label(let label):
                        let expected = FlowExport.literal(label)
                        let forms = ElementQuery.forms(of: label)
                        guard forms.count == 1 else {
                            return [
                                element,
                                "let expectation = XCTNSPredicateExpectation(predicate: \(FlowExport.predicate("label", "==", forms)), object: element)",
                                "_ = XCTWaiter.wait(for: [expectation], timeout: \(timeout))",
                                "XCTAssertTrue([\(forms.map(FlowExport.literal).joined(separator: ", "))].contains(element.label))",
                            ]
                        }
                        return [
                            element, "_ = element.wait(for: \\.label, toEqual: \(expected), timeout: \(timeout))",
                            "XCTAssertEqual(element.label, \(expected))",
                        ]
                    case .value(let value) where ElementQuery.forms(of: value).count > 1:
                        let forms = ElementQuery.forms(of: value)
                        return [
                            element,
                            "let expectation = XCTNSPredicateExpectation(predicate: \(FlowExport.predicate("value", "==", forms)), object: element)",
                            "_ = XCTWaiter.wait(for: [expectation], timeout: \(timeout))",
                            "XCTAssertTrue([\(forms.map(FlowExport.literal).joined(separator: ", "))].contains(element.value as? String ?? \"\"))",
                        ]
                    case .value(let value):
                        // flow run reads a missing value as "".
                        let expected = FlowExport.literal(value)
                        let format = value.isEmpty ? "value == nil OR value == %@" : "value == %@"
                        return [
                            element,
                            "let expectation = XCTNSPredicateExpectation(predicate: NSPredicate(format: \"\(format)\", \(expected)), object: element)",
                            "_ = XCTWaiter.wait(for: [expectation], timeout: \(timeout))",
                            "XCTAssertEqual(element.value as? String ?? \"\", \(expected))",
                        ]
                }
            case .settle:
                throw Unsupported(reason: "XCUIAutomation has no public wait for the screen to settle.")
            case .screenshot(let name):
                return [
                    "let attachment = XCTAttachment(screenshot: XCUIScreen.main.screenshot())",
                    "attachment.name = \(FlowExport.literal(name ?? "screenshot"))",
                    "attachment.lifetime = .keepAlways",
                    "activity.add(attachment)",
                ]
            case .alert(let button):
                let buttons = "springboard.alerts.buttons.matching(NSPredicate(format: \"label == %@\", \(FlowExport.literal(button))))"
                return [
                    "let springboard = XCUIApplication(bundleIdentifier: \"com.apple.springboard\")",
                    "uniqueElement(\(buttons), timeout: \(timeout)).tap()",
                ]
        }
    }

    /// `uniqueElement(...)` for a query target. Throws for a point.
    private func element(_ target: ElementTarget, _ timeout: String) throws(Unsupported) -> String {
        guard let query = target.query else { throw Unsupported(reason: "this step needs an element, not a point.") }
        return "uniqueElement(\(try self.query(query)), timeout: \(timeout))"
    }

    /// The XCUIElementQuery the runner builds for `query`.
    private func query(_ query: ElementQuery) throws(Unsupported) -> String {
        let type = query.type ?? "any"
        guard FlowExport.elementTypes.contains(type) else { throw Unsupported(reason: "\(type) is not an element type.") }
        var expression = "app.descendants(matching: .\(type))"
        if let id = query.id { expression += ".matching(identifier: \(FlowExport.literal(id)))" }
        if let label = query.label { expression += ".matching(\(FlowExport.predicate("label", "==", ElementQuery.forms(of: label))))" }
        if let contains = query.labelContains {
            expression += ".matching(\(FlowExport.predicate("label", "CONTAINS[c]", ElementQuery.forms(of: contains))))"
        }
        return expression
    }

    private static func coordinate(_ point: WirePoint) -> String {
        "app.coordinate(withNormalizedOffset: .zero).withOffset(CGVector(dx: \(number(point.x)), dy: \(number(point.y))))"
    }

    private static func seconds(_ ms: Int) -> String {
        number(Double(ms) / 1000)
    }

    private static func number(_ value: Double) -> String {
        value == value.rounded() ? String(Int(value)) : String(value)
    }
}

extension FlowStep {
    /// Whether the exported step uses the `app` variable.
    fileprivate var usesApp: Bool {
        switch action {
            case .ui(.press), .ui(.openURL), .ui(.sleep), .screenshot, .alert, .settle: false
            default: true
        }
    }
}

extension FlowCommands {
    /// `deviceloop flow export`: writes the flow as a new XCTest source file. `app` replaces app.bundleID. Refuses to replace a file.
    public static func export(_ json: JSONValue, to file: URL, className: String? = nil, app: String? = nil) throws -> CommandResult {
        let flow = try Flow(overriding(json, app: app, timeoutMs: nil))
        let file = file.absoluteURL
        guard file.pathExtension == "swift" else {
            throw DeviceLoopError(
                .badArguments, "\(file.path) is not a .swift file.", fix: "Pass a new .swift file, for example -o LoginFlowTests.swift.")
        }
        let output = try FlowExport.source(flow, className: className)
        do {
            try Data(output.source.utf8).write(to: file, options: .withoutOverwriting)
        } catch let error as CocoaError where error.code == .fileWriteFileExists {
            throw DeviceLoopError(
                .badArguments, "\(file.path) already exists.", fix: "Pass a new file name, or move the existing file first.")
        } catch {
            throw DeviceLoopError(
                .badArguments, "Could not write \(file.path).", fix: "Pass a path in a folder that exists.",
                detail: error.localizedDescription)
        }
        let text =
            ["flow \(flow.name) exported as \(output.className): \(output.supported.count) steps, \(output.fragile.count) fragile"]
            + output.fragile.map { "fragile \($0)" } + ["saved \(file.path)"]
        let payload: JSONValue = [
            "name": .string(flow.name),
            "class": .string(output.className),
            "file": .string(file.path),
            "supported": .array(output.supported.map(JSONValue.string)),
            "fragile": .array(output.fragile.map(JSONValue.string)),
        ]
        return CommandResult(text: text.joined(separator: "\n"), json: payload, files: [file])
    }
}
